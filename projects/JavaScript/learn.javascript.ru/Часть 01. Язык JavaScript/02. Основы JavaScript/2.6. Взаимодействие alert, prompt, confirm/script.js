'use strict';

// # alert, prompt, confirm

// Методы `alert`, `prompt` и `confirm` — это встроенные в браузер функции, которые позволяют 
// взаимодействовать с пользователем через модальные окна. Они **не являются частью стандарта Node.js**,
// поэтому их использование ограничено средой браузера. Это важно понимать, поскольку в чистом 
// JavaScript на сервере или в других средах эти функции недоступны.

// ## 🔥 `alert`

// Метод `alert` показывает модальное окно с сообщением и кнопкой "OK". Он используется для вывода 
// информации и блокирует выполнение кода до тех пор, пока пользователь не закроет окно.

// 🔥 1.1 - Простое уведомление
// Запрещено использовать в Node.js
alert("Привет, мир!");

// ## 🔥 prompt

// Метод prompt отображает диалоговое окно с текстовым полем для ввода информации. Он возвращает 
// строку, которую ввел пользователь, или null, если пользователь нажал "Отмена" или закрыл окно.

// 🔥 2.1 - Запрос имени
/*
   prompt() всегда возвращает строку или null.
   Даже если ввести число, оно вернется как строка.
*/
let name = prompt("Как вас зовут?", "Гость");
alert(`🔹 2.1.1 - ${name}`); // "Гость" или введенное значение

// 🔥 2.2 - Преобразование типа
/*
   Если нужно получить число, всегда нужно явно преобразовывать тип.
   parseInt() или Number() подходят для этой задачи.
*/
let year = prompt("Сколько вам лет?", 18);
alert(`🔹 2.2.1 - ${typeof year}`); // "string"
alert(`🔹 2.2.2 - ${typeof Number(year)}`); // "number"

// ## 🔥 confirm

// Метод confirm показывает модальное окно с сообщением и двумя кнопками: "OK" и "Отмена". 
// Он возвращает true, если пользователь нажал "OK", и false, если нажал "Отмена" или закрыл окно.

// 🔥 3.1 - Подтверждение действия
let isConfirmed = confirm("Вы согласны?");
alert(`🔹 3.1.1 - ${isConfirmed}`); // true или false

// ## 💡 Ключевые выводы

// alert, prompt, confirm — это API браузера, и они не работают в Node.js.

// Эти методы блокируют выполнение скрипта, что может негативно сказаться на пользовательском опыте, поэтому их следует использовать с осторожностью.

// Результат prompt() всегда является строкой. Для получения числового значения необходимо выполнять явное преобразование типов.

