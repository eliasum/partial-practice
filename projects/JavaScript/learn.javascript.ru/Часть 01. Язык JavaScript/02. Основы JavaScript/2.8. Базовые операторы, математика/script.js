'use strict';

// # Операторы в JavaScript

// Операторы — это специальные символы, которые выполняют операции над значениями или переменными (операндами). 
// Они составляют основу любой программы, позволяя выполнять вычисления, сравнения и логические операции.

// ## 🔥 Математические операторы

// Эти операторы используются для выполнения математических вычислений.

// 🔥 1.1 - Основные операции
let x = 10;
let y = 3;
console.log(`🔹 1.1.1 - Сложение: ${x + y}`); // 13
console.log(`🔹 1.1.2 - Вычитание: ${x - y}`); // 7
console.log(`🔹 1.1.3 - Умножение: ${x * y}`); // 30
console.log(`🔹 1.1.4 - Деление: ${x / y}`); // 3.333...
console.log(`🔹 1.1.5 - Остаток от деления: ${x % y}`); // 1

// 🔥 1.2 - Возведение в степень
let a = 2;
console.log(`🔹 1.2.1 - Возведение в степень: ${a ** 3}`); // 8 (2*2*2)

// 🔥 1.3 - Инкремент и декремент
let i = 5;
i++; // постфиксный инкремент
console.log(`🔹 1.3.1 - ${i}`); // 6
--i; // префиксный декремент
console.log(`🔹 1.3.2 - ${i}`); // 5

// ## 🔥 Операторы сравнения

// Операторы сравнения возвращают булево значение: true или false.

// 🔥 2.1 - Основные сравнения
console.log(`🔹 2.1.1 - Больше: ${5 > 3}`); // true
console.log(`🔹 2.1.2 - Меньше: ${5 < 3}`); // false
console.log(`🔹 2.1.3 - Равно: ${5 == 5}`); // true

// 🔥 2.2 - Строгое и нестрогое равенство
/*
   Нестрогое равенство (==) пытается преобразовать типы операндов
   перед сравнением.
   Строгое равенство (===) сравнивает значения и типы без преобразования.
*/
console.log(`🔹 2.2.1 - Нестрогое равенство: ${5 == "5"}`); // true
console.log(`🔹 2.2.2 - Строгое равенство: ${5 === "5"}`); // false

// 🔥 2.3 - Неравенство
console.log(`🔹 2.3.1 - Нестрогое: ${5 != 3}`); // true
console.log(`🔹 2.3.2 - Строгое: ${5 !== "5"}`); // true

// ## 🔥 Логические операторы

// Логические операторы используются для объединения или инвертирования булевых значений.

// 🔥 3.1 - И (AND)
/*
   Оператор && возвращает true, если оба операнда истинны.
   В противном случае — false.
*/
console.log(`🔹 3.1.1 - ${true && true}`); // true
console.log(`🔹 3.1.2 - ${true && false}`); // false

// 🔥 3.2 - ИЛИ (OR)
/*
   Оператор || возвращает true, если хотя бы один операнд истинен.
   В противном случае — false.
*/
console.log(`🔹 3.2.1 - ${true || false}`); // true
console.log(`🔹 3.2.2 - ${false || false}`); // false

// 🔥 3.3 - НЕ (NOT)
/*
   Оператор ! инвертирует булево значение операнда.
*/
console.log(`🔹 3.3.1 - ${!true}`); // false
console.log(`🔹 3.3.2 - ${!false}`); // true

// ## 🔥 Оператор объединения с null (??)

// Оператор ?? возвращает первый операнд, если он не равен null или undefined. В противном случае — второй.

// 🔥 4.1 - Применение оператора ??
let user = null;
let defaultUser = "Гость";
let currentUser = user ?? defaultUser;
console.log(`🔹 4.1.1 - ${currentUser}`); // "Гость"

let name = "Elijah";
let currentName = name ?? defaultUser;
console.log(`🔹 4.1.2 - ${currentName}`); // "Elijah"

// ## 💡 Ключевые выводы

// Всегда используйте строгое равенство (`===`), чтобы избежать неожиданных ошибок, связанных с неявным приведением типов.

// Операторы && и || имеют "короткое замыкание" (short-circuiting): они прекращают вычисление, как только результат становится ясен.

// Оператор ?? полезен для предоставления значений по умолчанию и отличается от || тем, что обрабатывает только null и undefined.

