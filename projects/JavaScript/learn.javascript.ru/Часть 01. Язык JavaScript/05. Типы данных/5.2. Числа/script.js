'use strict';

// 🔥 1. Основные понятия о числах
console.log(`🔹 1.1 - ${typeof 10}`); // "number" (тип числа)
console.log(`🔹 1.2 - ${typeof 3.14}`); // "number" (дробные числа тоже 'number')

// 🔥 2. Способы записи чисел
console.log(`🔹 2.1 - Десятичные: ${256}`); // 256 (обычные числа)
console.log(`🔹 2.2 - Шестнадцатеричные: ${0xff}`); // 255 (начинаются с 0x)
console.log(`🔹 2.3 - Двоичные: ${0b101}`); // 5 (начинаются с 0b)
console.log(`🔹 2.4 - Восьмеричные: ${0o10}`); // 8 (начинаются с 0o)

// 🔥 3. Специальные числовые значения
console.log(`🔹 3.1 - Infinity: ${1 / 0}`); // Infinity (бесконечность)
console.log(`🔹 3.2 - NaN: ${"не число" / 2}`); // NaN (Not a Number - результат ошибки вычислений)

// 🔥 4. Преобразование строк в числа
/*
  Number() - преобразует строку в число целиком
  parseInt() - извлекает целое число (игнорирует нечисловые символы после числа)
  parseFloat() - извлекает дробное число
*/
console.log(`🔹 4.1 - Number("123"): ${Number("123")}`); // 123 (строгое преобразование)
console.log(`🔹 4.2 - parseInt("100px"): ${parseInt("100px")}`); // 100 (извлекает число из строки)
console.log(`🔹 4.3 - parseFloat("12.5em"): ${parseFloat("12.5em")}`); // 12.5 (извлекает дробное число)

// 🔥 5. Проверка на число
/*
  isNaN() - проверяет, является ли значение NaN (предварительно преобразует в число)
  isFinite() - проверяет, является ли значение конечным числом
  Number.isInteger() - проверяет, является ли число целым
*/
console.log(`🔹 5.1 - isNaN(NaN): ${isNaN(NaN)}`); // true (проверка на "не число")
console.log(`🔹 5.2 - isFinite("15"): ${isFinite("15")}`); // true (конечное число)
console.log(`🔹 5.3 - Number.isInteger(10.0): ${Number.isInteger(10.0)}`); // true (10.0 считается целым)

// 🔥 6. Математические операции
console.log(`🔹 6.1 - 0.1 + 0.2: ${0.1 + 0.2}`); // 0.30000000000000004 (проблема точности)
console.log(`🔹 6.2 - 10 / 3: ${10 / 3}`); // 3.3333333333333335 (бесконечные дроби)
console.log(`🔹 6.3 - 2 ** 10: ${2 ** 10}`); // 1024 (возведение в степень)

// 🔥 7. Методы чисел
const num = 12.34;
/*
  toFixed(n) - округляет число до n знаков после запятой, возвращает строку
  toString(base) - преобразует число в строку в системе счисления base (2-36)
*/
console.log(`🔹 7.1 - num.toFixed(1): ${num.toFixed(1)}`); // "12.3" (округление до 1 знака)
console.log(`🔹 7.2 - num.toString(2): ${num.toString(2)}`); // Двоичное представление

// 🔥 8. Math - встроенный объект
/*
  Math содержит математические константы и функции
  Math.random() - случайное число от 0 (включительно) до 1 (не включая)
  Math.max()/min() - находит максимальное/минимальное число из аргументов
*/
console.log(`🔹 8.1 - Math.PI: ${Math.PI}`); // 3.141592653589793 (число π)
console.log(`🔹 8.2 - Math.random(): ${Math.random()}`); // Случайное число 0..1
console.log(`🔹 8.3 - Math.max(1, 5, 3): ${Math.max(1, 5, 3)}`); // 5 (максимальное из чисел)

// 💡 Полезные примеры:
// Функция проверки, является ли значение числом
function isNumeric(value) {
  /*
    parseFloat пытается преобразовать в число
    isFinite проверяет, что это не Infinity/NaN
    !isNaN исключает случай, когда parseFloat вернул NaN
  */
  return !isNaN(parseFloat(value)) && isFinite(value);
}
console.log(`🔹 9.1 - isNumeric("123"): ${isNumeric("123")}`); // true
console.log(`🔹 9.2 - isNumeric("12z"): ${isNumeric("12z")}`); // false

// Округление до 2 знаков после запятой
const price = 12.3456;
/*
  Умножаем на 100, округляем, затем делим на 100
  Это стандартный способ округления до N знаков
*/
console.log(`🔹 9.3 - Округление: ${Math.round(price * 100) / 100}`); // 12.35

// Дополнительные пояснения:

//     IEEE-754 - стандарт представления чисел с плавающей точкой, объясняющий неточности в вычислениях

//     Системы счисления:

//         Шестнадцатеричная (0-9, A-F) полезна для цветов, кодировок

//         Двоичная (0-1) - основа работы компьютеров

//         Восьмеричная (0-7) - редко используется

//     Методы округления:

//         Math.floor() - в меньшую сторону

//         Math.ceil() - в большую сторону

//         Math.round() - по правилам математики

//     Точность вычислений:

//         Проблема 0.1 + 0.2 возникает из-за двоичного представления дробей

//         Для денег лучше использовать целые центы вместо дробных долларов

//     Преобразование типов:

//         Явное (Number()) vs неявное (использование в математических операциях)

//         parseInt может принимать второй параметр - систему счисления