// # Map и Set в JavaScript

// `Map` и `Set` — это встроенные в JavaScript коллекции, появившиеся в ES6. Они 
// предлагают более гибкие и специализированные подходы к хранению данных по 
// сравнению с обычными объектами и массивами.


// ## 🔥 Map

// `Map` — это коллекция для хранения пар "ключ-значение", где в качестве 
// ключей могут выступать любые типы данных, а не только строки.

// ### 1. Основные методы Map

// 🔥 1.1 - Создание и заполнение Map
let map = new Map();
map.set('1', 'str1');   // Ключ-строка
map.set(1, 'num1');     // Ключ-число
map.set(true, 'bool1'); // Ключ-булево значение
map.set({a: 1}, 'obj1'); // Ключ-объект

// 🔥 1.2 - Получение и проверка значений
console.log(`🔹 1.2.1 - Получение значения: ${map.get(1)}`); // "num1"
console.log(`🔹 1.2.2 - Проверка наличия: ${map.has(true)}`); // true

// 🔥 1.3 - Удаление и размер
map.delete('1');
console.log(`🔹 1.3.1 - Размер Map: ${map.size}`); // 3
map.clear(); // Очистка всей коллекции
console.log(`🔹 1.3.2 - Размер после очистки: ${map.size}`); // 0

// ### 2. Итерация по Map

// Map поддерживает итерацию с помощью for...of, а также имеет методы keys(), values() и entries().

// 🔥 2.1 - Итерация по ключам и значениям
let recipe = new Map([
  ['apple', 500],
  ['carrot', 300],
  ['potato', 100],
]);

for (let key of recipe.keys()) {
   console.log(key); // "apple", "carrot", "potato"
}

for (let value of recipe.values()) {
   console.log(value); // 500, 300, 100
}

// 🔥 2.2 - Итерация по парам "ключ-значение"
for (let entry of recipe) {
   console.log(entry); // ["apple", 500], ["carrot", 300], ["potato", 100]
}

// ## 🔥 Set

// Set — это коллекция для хранения уникальных значений. Каждый элемент в Set может встречаться только один раз.

// ### 1. Основные методы Set

// 🔥 3.1 - Создание и добавление элементов
let set = new Set();
set.add('a');
set.add('b');
set.add('a'); // Повторное добавление игнорируется

// 🔥 3.2 - Размер и проверка
console.log(`🔹 3.2.1 - Размер Set: ${set.size}`); // 2
console.log(`🔹 3.2.2 - Проверка наличия: ${set.has('b')}`); // true

// 🔥 3.3 - Удаление
set.delete('a');
console.log(`🔹 3.3.1 - Размер после удаления: ${set.size}`); // 1

// ### 2. Итерация по Set

// Set также поддерживает итерацию с помощью for...of, а также имеет те же методы 
// keys(), values() и entries(), которые, по сути, возвращают одно и то же.

// 🔥 4.1 - Итерация по Set
let uniqueFruits = new Set(["apple", "banana", "orange"]);
for (let fruit of uniqueFruits) {
   console.log(fruit); // "apple", "banana", "orange"
}

