'use strict';

// # Массивы в JavaScript

// Массивы — это специальные объекты, предназначенные для хранения упорядоченных коллекций значений. 
// Их можно создавать с помощью квадратных скобок `[]` или конструктора `new Array()`. Массивы в 
// JavaScript могут содержать элементы любых типов данных.

// ## 🔥 Создание и доступ к элементам

// 🔥 1.1 - Создание массива
let fruits = ["Apple", "Orange", "Plum"];

// 🔥 1.2 - Доступ к элементу по индексу
/*
   Массивы имеют числовые индексы, начинающиеся с 0.
   Свойство length возвращает количество элементов.
*/
console.log(`🔹 1.2.1 - Первый элемент: ${fruits[0]}`); // "Apple"
console.log(`🔹 1.2.2 - Последний элемент: ${fruits[fruits.length-1]}`); // "Plum"

// 🔥 1.3 - Добавление и удаление элементов
fruits[3] = "Lemon"; // Добавление по индексу
console.log(`🔹 1.3.1 - Добавление: ${fruits}`); // ["Apple", "Orange", "Plum", "Lemon"]
fruits.length = 2; // Удаление элементов с конца
console.log(`🔹 1.3.2 - Уменьшение длины: ${fruits}`); // ["Apple", "Orange"]
fruits.length = 4; // Затем увеличение длины
console.log(`🔹 1.3.3 - Снова увеличение длины: ${fruits}`); // ["Apple", "Orange",,]
fruits.length = 2; // Удаление элементов с конца
console.log(`🔹 1.3.4 - Уменьшение длины: ${fruits}`); // ["Apple", "Orange"]

// ## 🔥 Методы для работы с массивами

// 1. Добавление и удаление элементов
// Методы push, pop, shift и unshift позволяют эффективно управлять элементами в начале и конце массива.

// 🔥 2.1 - push/pop
/*
   push() - добавляет элемент в конец массива.
   pop() - удаляет последний элемент и возвращает его.
*/
let stack = [1, 2];
stack.push(3);
console.log(`🔹 2.1.1 - push: ${stack}`); // [1, 2, 3]
console.log(`🔹 2.1.2 - pop: ${stack.pop()}`); // 3
console.log(`🔹 2.1.3 - После pop: ${stack}`); // [1, 2]

// 🔥 2.2 - shift/unshift
/*
   shift() - удаляет первый элемент и возвращает его.
   unshift() - добавляет элемент в начало массива.
*/
let queue = ["a","b"];
queue.unshift("c");
console.log(`🔹 2.2.1 - unshift: ${queue}`); // ["c", "a", "b"]
console.log(`🔹 2.2.2 - shift: ${queue.shift()}`); // "c"
console.log(`🔹 2.2.3 - После shift: ${queue}`); // ["a", "b"]

// 2. Итерация по массиву
// Существует несколько способов перебора элементов массива.

// 🔥 3.1 - Цикл for...of
for (let fruit of fruits){
   console.log(fruit); // "Apple", "Orange"
}

// 🔥 3.2 - Метод forEach
fruits.forEach((item, index) => {
   console.log(`Индекс: ${index}, Значение: ${item}`);
});

// ## 🔥 Особенности массивов

// В отличие от массивов в других языках, массивы в JavaScript являются динамическими и не требуют 
// указания размера при создании. Также они являются специальными объектами, поэтому могут иметь 
// дополнительные свойства, но это не рекомендуется.

// 🔥 4.1 - Массив как объект
let arr = ["test"];
arr.testProperty = 5;
console.log(`🔹 4.1.1 - arr.testProperty: ${arr.testProperty}`); // 5

// ## 💡 Ключевые выводы

// Массивы в JavaScript — это динамические коллекции.

// Доступ к элементам осуществляется по числовым индексам, начиная с нуля.

// Методы push/pop (работа с концом) и shift/unshift (работа с началом) позволяют эффективно добавлять и удалять элементы.

// Для перебора массива рекомендуется использовать for...of или forEach.

