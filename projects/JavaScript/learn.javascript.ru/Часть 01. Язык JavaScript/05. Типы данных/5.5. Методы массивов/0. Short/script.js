'use strict';

// # Методы массивов в JavaScript

// JavaScript предоставляет обширный набор методов для работы с массивами, которые 
// позволяют выполнять различные операции, такие как добавление/удаление элементов, 
// поиск, фильтрация, трансформация и агрегация данных. Эти методы значительно 
// упрощают написание чистого и выразительного кода.

// ## 🔥 Добавление, удаление и изменение

// В дополнение к `push`, `pop`, `shift` и `unshift`, существуют методы, позволяющие 
// работать с элементами в середине массива.

// ### 1. `splice`

// Метод `splice` — это мощный инструмент для изменения массива: он может удалять, 
// заменять и добавлять элементы, начиная с указанного индекса.

// 🔥 1.1 - Удаление элементов
let arr1 = ["I", "study", "JavaScript"];
arr1.splice(1, 1); // Удаляет 1 элемент, начиная с индекса 1
console.log(`🔹 1.1.1 - После удаления: ${arr1}`); // ["I", "JavaScript"]

// 🔥 1.2 - Замена элементов
let arr2 = ["I", "am", "learning", "JS"];
arr2.splice(1, 2, "love"); // Удаляет 2 элемента, добавляет "love"
console.log(`🔹 1.2.1 - После замены: ${arr2}`); // ["I", "love", "JS"]

// 🔥 1.3 - Добавление элементов без удаления
let arr3 = [1, 2, 5];
arr3.splice(2, 0, 3, 4); // Удаляет 0 элементов, добавляет 3 и 4
console.log(`🔹 1.3.1 - После добавления: ${arr3}`); // [1, 2, 3, 4, 5]

// ### 2. slice

// Метод slice создает новый массив, копируя в него часть исходного массива от start до end (не включая end).

// 🔥 2.1 - Копирование части массива
let arr4 = ["t", "e", "s", "t"];
let sliced = arr4.slice(1, 3); // Копирует элементы с индекса 1 по 2
console.log(`🔹 2.1.1 - Копия: ${sliced}`); // ["e", "s"]

// ### 3. concat

// Метод concat объединяет массив с другими массивами или значениями, возвращая новый массив.

// 🔥 3.1 - Объединение массивов
let arr5 = [1, 2];
let newArr = arr5.concat([3, 4], 5);
console.log(`🔹 3.1.1 - Объединенный массив: ${newArr}`); // [1, 2, 3, 4, 5]

// ## 🔥 Поиск в массиве

// ### 1. indexOf, lastIndexOf, includes

// Эти методы ищут элементы и возвращают их индекс или булево значение.

// 🔥 4.1 - Поиск
let fruits = ["Apple", "Orange", "Apple"];
console.log(`🔹 4.1.1 - Индекс 'Apple': ${fruits.indexOf("Apple")}`); // 0
console.log(`🔹 4.1.2 - Последний индекс 'Apple': ${fruits.lastIndexOf("Apple")}`); // 2
console.log(`🔹 4.1.3 - Содержит 'Orange': ${fruits.includes("Orange")}`); // true

// ### 2. find и findIndex

// Методы find и findIndex ищут элемент, который удовлетворяет условию, заданному в функции обратного вызова.

// 🔥 5.1 - Поиск объекта по условию
let users1 = [
  {id: 1, name: "John"},
  {id: 2, name: "Pete"},
  {id: 3, name: "Mary"}
];

let user = users1.find(item => item.id == 2);
console.log(`🔹 5.1.1 - Найденный пользователь: ${user.name}`); // "Pete"

let index = users1.findIndex(item => item.id == 3);
console.log(`🔹 5.1.2 - Индекс пользователя: ${index}`); // 2

// ## 🔥 Трансформация и перебор

// ### 1. map

// Метод map создает новый массив, применяя функцию к каждому элементу исходного массива.

// 🔥 6.1 - Преобразование в массив длин
let names = ["Bilbo", "Gandalf", "Nazgul"];
let lengths = names.map(item => item.length);
console.log(`🔹 6.1.1 - Длины имен: ${lengths}`); // [5, 7, 6]

// ### 2. filter

// Метод filter создает новый массив, содержащий только те элементы, для которых
// функция обратного вызова вернула true.

// 🔥 7.1 - Фильтрация пользователей
let users = [
  {id: 1, name: "John"},
  {id: 2, name: "Pete"},
  {id: 3, name: "Mary"}
];

let filteredUsers = users.filter(item => item.id < 3);
console.log(`🔹 7.1.1 - Отфильтрованные пользователи: ${filteredUsers.length}`); // 2

// ### 3. reduce

// Метод reduce "сводит" массив к одному значению, выполняя функцию-редуктор для каждого элемента.

// 🔥 8.1 - Суммирование элементов
let arr = [1, 2, 3, 4, 5];
let sum = arr.reduce((accumulator, current) => accumulator + current, 0);
console.log(`🔹 8.1.1 - Сумма: ${sum}`); // 15

// ## 💡 Ключевые выводы

// Большинство методов массивов (map, filter, slice, concat) возвращают новый массив, 
// не изменяя исходный. Это соответствует принципам иммутабельности и упрощает отладку.

// splice является единственным методом, который изменяет сам массив.

// Методы map, filter, reduce (MRF) образуют ядро функционального программирования в 
// JavaScript и являются обязательными для освоения.

