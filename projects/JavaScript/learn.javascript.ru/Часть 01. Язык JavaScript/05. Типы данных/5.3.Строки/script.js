'use strict';

// # Работа со строками в JavaScript

// В JavaScript строки — это последовательности символов, используемые для представления текстовых данных. 
// Они могут быть созданы с помощью одинарных (`'...'`), двойных (`"..."`) или обратных кавычек (`` `...` ``). 
// Последние позволяют использовать **шаблонные строки** (template literals) для вставки переменных и многострочных значений.

// ---
// ## 🔥 Доступ к символам и длина строки

// Каждый символ в строке имеет свой индекс, начиная с `0`. Свойство `length` возвращает общее количество символов.

// 🔥 1.1 - Доступ к символам
let str = "Hello";
console.log(`🔹 1.1.1 - ${str[0]}`); // "H"
console.log(`🔹 1.1.2 - ${str.at(0)}`); // "H" (новый, более гибкий метод)

// 🔥 1.2 - Длина строки
console.log(`🔹 1.2.1 - ${str.length}`); // 5

// ## 🔥 Поиск и проверка содержимого

// Методы indexOf, lastIndexOf, includes, startsWith и endsWith позволяют искать подстроки или проверять их наличие.

// 🔥 2.1 - Поиск подстроки
let sentence = "Hello, world!";
console.log(`🔹 2.1.1 - ${sentence.indexOf("world")}`); // 7 (индекс начала подстроки)
console.log(`🔹 2.1.2 - ${sentence.indexOf("World")}`); // -1 (регистрозависимый поиск)
console.log(`🔹 2.1.3 - ${sentence.includes("world")}`); // true

// 🔥 2.2 - Проверка начала и конца строки
console.log(`🔹 2.2.1 - ${sentence.startsWith("Hello")}`); // true
console.log(`🔹 2.2.2 - ${sentence.endsWith("!")}`); // true

// ## 🔥 Изменение и преобразование

// Методы строк не изменяют исходную строку, а всегда возвращают новую.

// 🔥 3.1 - Изменение регистра
let text = "JavaScript";
console.log(`🔹 3.1.1 - ${text.toUpperCase()}`); // "JAVASCRIPT"
console.log(`🔹 3.1.2 - ${text.toLowerCase()}`); // "javascript"

// 🔥 3.2 - Извлечение подстроки
/*
  slice(start, end) - извлекает часть строки. `end` не включается в результат.
  substring(start, end) - похож на slice, но не работает с отрицательными аргументами.
*/
console.log(`🔹 3.2.1 - ${text.slice(0, 4)}`); // "Java"
console.log(`🔹 3.2.2 - ${text.substring(4)}`); // "Script"

// 🔥 3.3 - Замена и удаление
let phrase = "I am learning JS.";
console.log(`🔹 3.3.1 - ${phrase.replace("JS", "JavaScript")}`); // "I am learning JavaScript."

let spaces = "  trim me  ";
console.log(`🔹 3.3.2 - ${spaces.trim()}`); // "trim me"

// ## 💡 Ключевые выводы

// Строки в JS неизменяемы. Все методы, которые "изменяют" строку, на самом деле возвращают новую.

// Используйте шаблонные строки `${…}` для удобной интерполяции переменных и создания многострочных строк.

// Для надежного доступа к символам лучше использовать str.at(index), так как он корректно обрабатывает отрицательные индексы.

