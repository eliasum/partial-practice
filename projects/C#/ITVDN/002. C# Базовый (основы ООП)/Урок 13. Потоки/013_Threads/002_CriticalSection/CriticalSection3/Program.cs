using System;
using System.Threading;

// КРИТИЧЕСКАЯ СЕКЦИЯ (CRITICAL SECTION) - базовый паттерн синхронизации потоков
// Назначение: предотвращение одновременного доступа нескольких потоков к разделяемому ресурсу
// В данном примере разделяемый ресурс - объект Console (стандартный вывод)

namespace CriticalSection
{
    class Program
    {
        /*
        ОБЪЕКТ БЛОКИРОВКИ (LOCK OBJECT) - фундаментальный элемент синхронизации:
        
        - static object locker = new object(): 
          * static - объект ЕДИНЫЙ для всех экземпляров класса и потоков
          * object - базовый тип, используемый исключительно как маркер блокировки
          * locker - не содержит данных, используется только для координации потоков
        
        - Принцип работы:
          * Каждый поток при входе в lock(locker) пытается захватить монитор объекта locker
          * Только один поток может одновременно владеть монитором
          * Остальные потоки БЛОКИРУЮТСЯ на lock(locker) до освобождения монитора
        
        - Важные особенности:
          * Объект блокировки должен быть private/protected в реальных приложениях
          * Использование public объектов для блокировки может привести к deadlock
          * В данном примере static обеспечивает единую точку синхронизации для всех потоков
        */
        static object locker = new object();

        // МЕТОД WRITESECOND - код, выполняемый ВТОРИЧНЫМ потоком:
        // - Вызывается асинхронно в контексте созданного потока
        // - Конкурирует с главным потоком за доступ к ресурсу Console
        static void WriteSecond()
        {
            // ЦИКЛ ИЗ 20 ИТЕРАЦИЙ - имитирует продолжительную работу потока:
            // Каждая итерация представляет отдельную операцию с разделяемым ресурсом
            for (int i = 0; i < 20; i++)
            {
                /*
                КРИТИЧЕСКАЯ СЕКЦИЯ - участок кода с эксклюзивным доступом:
                
                - Назначение: гарантировать, что операции с Console выполняются атомарно
                - Без lock: вывод двух потоков перемешивается (состояние гонки)
                - С lock: каждая группа вывода сохраняет целостность
                */

                /*НАЧАЛО КРИТИЧЕСКОЙ СЕКЦИИ*/

                // КОНСТРУКЦИЯ LOCK - синхронизирует доступ к блоку кода:
                // - При входе: автоматически вызывает Monitor.Enter(locker)
                // - При выходе: автоматически вызывает Monitor.Exit(locker) в finally
                // - Гарантирует освобождение блокировки даже при исключениях
                lock (locker)
                {
                    // РАЗДЕЛЯЕМЫЙ РЕСУРС - объект Console:
                    // Все потоки пытаются изменить цвет и выводить данные одновременно

                    // Console.ForegroundColor - изменение цвета текста:
                    // - Без синхронизации: цвета могут "перемешиваться" между потоками
                    // - Поток устанавливает желтый цвет для своего вывода
                    Console.ForegroundColor = ConsoleColor.Yellow;

                    // Console.WriteLine - вывод текста с отступом:
                    // - new string(' ', 10) - создает строку из 10 пробелов для отступа
                    // - "Secondary" - идентификатор вторичного потока
                    // - Без lock: текст может прерываться выводом главного потока
                    Console.WriteLine(new string(' ', 10) + "Secondary");

                    // Восстановление стандартного цвета:
                    // - Важно сбросить цвет, чтобы не влиять на другие потоки
                    Console.ForegroundColor = ConsoleColor.Gray;

                    // Thread.Sleep(100) - ИМИТАЦИЯ ПРОДОЛЖИТЕЛЬНОЙ РАБОТЫ:
                    // - Задержка 100мс увеличивает вероятность переключения контекста
                    // - Делает состояние гонки более заметным при тестировании
                    // - В реальных приложениях представляет время обработки данных
                    Thread.Sleep(100);
                }
                /*КОНЕЦ КРИТИЧЕСКОЙ СЕКЦИИ*/

                // После выхода из lock поток может быть сразу вытеснен планировщиком
                // Следующая итерация начнется с попытки захвата lock снова
            }
        }

        static void Main()
        {
            // НАСТРОЙКА ОКНА КОНСОЛИ для удобного отображения:
            // - Ширина 80 символов, высота 45 строк
            // - Обеспечивает комфортный просмотр параллельного вывода потоков
            Console.SetWindowSize(80, 45);

            /*
            СОЗДАНИЕ И ЗАПУСК ВТОРИЧНОГО ПОТОКА - подробная схема:
            
            ДЕТАЛЬНАЯ ЦЕПОЧКА СОЗДАНИЯ ПОТОКА:
            
            1. WriteSecond - целевой метод для выполнения в потоке
               * Сигнатура: void Method() - соответствует делегату ThreadStart
            
            2. ThreadStart writeSecond = new ThreadStart(WriteSecond)
               * ЯВНОЕ создание делегата ThreadStart
               * Делегат - объект, указывающий на метод WriteSecond
               * ThreadStart - специальный делегат для методов без параметров
            
            3. Thread thread = new Thread(writeSecond)
               * Создание объекта потока с указанием делегата
               * Поток создан, но еще не запущен
               * На данном этапе поток в состоянии "Unstarted"
            
            4. thread.Start()
               * Запуск потока - переход в состояние "Running"
               * Управление немедленно возвращается в главный поток
               * Далее выполняются ОБА потока параллельно
            
            АЛЬТЕРНАТИВНЫЙ (сокращенный) синтаксис:
            new Thread(WriteSecond).Start() - неявное создание делегата
            */

            // ШАГ 1: ЯВНОЕ СОЗДАНИЕ ДЕЛЕГАТА ThreadStart
            // Делегат связывает метод WriteSecond с механизмом создания потока
            ThreadStart writeSecond = new ThreadStart(WriteSecond);

            // ШАГ 2: СОЗДАНИЕ ОБЪЕКТА ПОТОКА
            // Передаем делегат в конструктор Thread - поток знает, какой метод выполнять
            Thread thread = new Thread(writeSecond);

            // ШАГ 3: ЗАПУСК ПОТОКА АСИНХРОННО
            // Важно: Start() НЕ блокирует главный поток
            // Управление сразу возвращается к следующей строке кода
            thread.Start();

            // ГЛАВНЫЙ ПОТОК - продолжает выполнение параллельно с вторичным:
            // Оба потока одновременно пытаются войти в критические секции
            for (int i = 0; i < 20; i++)
            {
                /*
                КРИТИЧЕСКАЯ СЕКЦИЯ ГЛАВНОГО ПОТОКА - аналогична вторичному:
                Оба потока используют ОДИН объект locker для синхронизации
                */

                /*НАЧАЛО КРИТИЧЕСКОЙ СЕКЦИИ*/
                lock (locker)
                {
                    // РАЗДЕЛЯЕМЫЙ РЕСУРС - тот же объект Console:
                    // Главный поток устанавливает зеленый цвет для своего вывода
                    Console.ForegroundColor = ConsoleColor.Green;

                    // Вывод без отступа - визуально отличаем от вторичного потока
                    Console.WriteLine("Primary");

                    // Восстановление стандартного цвета
                    Console.ForegroundColor = ConsoleColor.Gray;

                    // Аналогичная задержка для имитации работы
                    Thread.Sleep(100);
                }
                /*КОНЕЦ КРИТИЧЕСКОЙ СЕКЦИИ*/

                // МЕЖДУ ИТЕРАЦИЯМИ: поток может быть вытеснен, может захватить lock снова
                // или уступить его другому потоку - зависит от планировщика потоков ОС
            }

            // КОНЕЦ РАБОТЫ ГЛАВНОГО ПОТОКА:
            // Console.ReadKey() - ОЖИДАНИЕ ВВОДА ПОЛЬЗОВАТЕЛЯ:
            // - Предотвращает немедленное закрытие консоли
            // - Дает время для просмотра результатов
            // - Без этого приложение завершится после выхода из Main
            // - При завершении Main все фоновые потоки принудительно завершаются
            Console.ReadKey();

            // ВАЖНО: главный поток НЕ ожидает завершения вторичного потока явно
            // Если вторичный поток не завершится до ReadKey(), он будет убит при закрытии
        }
    }
}