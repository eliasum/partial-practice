"""
Python-аналог C# кода с критическими секциями для синхронизации двух потоков
Демонстрация работы с threading.Lock для координации доступа к разделяемому ресурсу
"""

import threading
import time
import sys

class ConsoleColors:
    """Класс для управления цветами консоли (аналог ConsoleColor в C#)"""
    GREEN = '\033[92m'
    YELLOW = '\033[93m'
    GRAY = '\033[90m'
    RESET = '\033[0m'

class CriticalSectionDemo:
    def __init__(self):
        """
        ИНИЦИАЛИЗАЦИЯ ОБЪЕКТА СИНХРОНИЗАЦИИ:
        
        - threading.Lock() - аналог object locker в C#
        - Lock - примитив синхронизации для управления доступом к критическим секциям
        - Не-static в отличие от C#, но используется одинаково через self
        """
        self.lock = threading.Lock()
    
    def write_secondary(self):
        """
        МЕТОД ДЛЯ ВТОРИЧНОГО ПОТОКА - аналог WriteSecond() в C#:
        Выполняет 20 итераций с выводом в консоль с синхронизацией
        """
        # ЦИКЛ ИЗ 20 ИТЕРАЦИЙ - полный аналог C# версии:
        for i in range(20):
            """
            КРИТИЧЕСКАЯ СЕКЦИЯ в Python с использованием with lock:
            - with self.lock: - автоматически вызывает acquire() при входе
            - Гарантированно вызывает release() при выходе (даже при исключениях)
            - Безопасная замена конструкции lock(locker) в C#
            """
            
            # НАЧАЛО КРИТИЧЕСКОЙ СЕКЦИИ
            with self.lock:
                # РАЗДЕЛЯЕМЫЙ РЕСУРС - стандартный вывод:
                # Используем ANSI-коды для цветного вывода (аналог Console.ForegroundColor)
                
                # Вывод с желтым цветом и отступом 10 пробелов
                print(f"{ConsoleColors.YELLOW}{' ' * 10}Secondary{ConsoleColors.RESET}")
                
                # time.sleep(0.1) - ИМИТАЦИЯ РАБОТЫ (100ms в C#):
                # Увеличивает вероятность переключения между потоками
                time.sleep(0.1)
            # КОНЕЦ КРИТИЧЕСКОЙ СЕКЦИИ (автоматический release())
            
            # После выхода из with lock поток может продолжить или быть вытесненным
    
    def run_main_thread(self):
        """
        КОД ГЛАВНОГО ПОТОКА - аналог цикла for в Main() в C#:
        Выполняет 20 итераций с синхронизированным выводом
        """
        for i in range(20):
            # КРИТИЧЕСКАЯ СЕКЦИЯ ГЛАВНОГО ПОТОКА:
            # Использует ТОТ ЖЕ объект lock для синхронизации
            with self.lock:
                # Вывод с зеленым цветом без отступа
                print(f"{ConsoleColors.GREEN}Primary{ConsoleColors.RESET}")
                
                # Аналогичная задержка для имитации работы
                time.sleep(0.1)

def main():
    """
    ГЛАВНАЯ ФУНКЦИЯ - аналог Main() в C#
    Создает и запускает потоки, управляет выполнением
    """
    
    # СОЗДАНИЕ ЭКЗЕМПЛЯРА ДЕМО-КЛАССА:
    # Содержит объект lock и методы для потоков
    demo = CriticalSectionDemo()
    
    """
    СОЗДАНИЕ И ЗАПУСК ВТОРИЧНОГО ПОТОКА в Python:
    
    ПРОЦЕСС СОЗДАНИЯ ПОТОКА (упрощенный по сравнению с C#):
    
    1. threading.Thread(target=demo.write_secondary)
       - target - прямая ссылка на метод (не нужен аналог делегата)
       - Поток создан в состоянии "не запущен"
    
    2. secondary_thread.start()
       - Запуск потока (аналог thread.Start() в C#)
       - Управление немедленно возвращается главному потоку
    
    ОТЛИЧИЯ ОТ C#:
    - Нет явного создания делегата ThreadStart
    - Прямая передача метода в конструктор потока
    """
    
    # ШАГ 1: СОЗДАНИЕ ОБЪЕКТА ПОТОКА
    # Указываем целевой метод demo.write_secondary
    secondary_thread = threading.Thread(target=demo.write_secondary)
    
    # ШАГ 2: ЗАПУСК ВТОРИЧНОГО ПОТОКА
    # Поток начинает выполнение асинхронно
    secondary_thread.start()
    
    # ШАГ 3: ВЫПОЛНЕНИЕ ГЛАВНОГО ПОТОКА
    # Главный поток продолжает работу ПАРАЛЛЕЛЬНО с вторичным
    demo.run_main_thread()
    
    # ОЖИДАНИЕ ЗАВЕРШЕНИЯ ВТОРИЧНОГО ПОТОКА:
    # В Python нужно ЯВНО ожидать завершения дочерних потоков
    # Иначе главный поток может завершиться раньше (убивая дочерние)
    secondary_thread.join()
    
    # ОЖИДАНИЕ ВВОДА ПОЛЬЗОВАТЕЛЯ (аналог Console.ReadKey()):
    input("\nНажмите Enter для выхода...")

# ТОЧКА ВХОДА В ПРИЛОЖЕНИЕ:
if __name__ == "__main__":
    main()