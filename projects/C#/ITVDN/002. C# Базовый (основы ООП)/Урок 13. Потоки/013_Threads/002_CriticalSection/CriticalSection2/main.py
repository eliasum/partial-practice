"""
Python-аналог C# кода с критической секцией на Monitor.Enter/Exit
Используем threading.Lock для аналогичной функциональности
"""

import threading
import time

class MyClass:
    def __init__(self):
        """
        ОБЪЕКТ БЛОКИРОВКИ в Python:
        - threading.Lock() аналогичен object block + Monitor в C#
        - Lock - примитив синхронизации для управления доступом к ресурсам
        """
        self.lock = threading.Lock()
    
    def method(self):
        """
        МЕТОД, ВЫПОЛНЯЕМЫЙ В ПОТОКЕ - аналог Method() в C#:
        - Вызывается одновременно из нескольких потоков
        - Использует lock для синхронизации доступа к разделяемому ресурсу
        """
        
        # ИДЕНТИФИКАТОР ПОТОКА в Python:
        # threading.current_thread().ident - аналог Thread.CurrentThread.GetHashCode()
        # ident - уникальный числовой идентификатор потока
        thread_hash = threading.current_thread().ident
        
        """
        КРИТИЧЕСКАЯ СЕКЦИЯ с явным lock.acquire()/release():
        - Аналог Monitor.Enter/Exit в C#
        - ОПАСНО: как и в C#, при исключении lock может не освободиться
        - В реальном коде используйте with lock: для безопасности
        """
        
        # НАЧАЛО КРИТИЧЕСКОЙ СЕКЦИИ
        # lock.acquire() - ПОПЫТКА ЗАХВАТА БЛОКИРОВКИ:
        # - Если lock свободен - захватывает и продолжает
        # - Если lock занят - блокируется до освобождения
        # - blocking=True (по умолчанию) - поток ждет бесконечно
        self.lock.acquire()  # Закомментировать для демонстрации гонки данных
        
        try:
            # ТЕЛО КРИТИЧЕСКОЙ СЕКЦИИ:
            # - Весь этот код выполняется ТОЛЬКО одним потоком одновременно
            # - Другие потоки ждут на lock.acquire()
            for counter in range(10):
                # РАЗДЕЛЯЕМЫЙ РЕСУРС - стандартный вывод:
                # - print() в Python потокобезопасен, но демонстрируем принцип
                # - Без синхронизации вывод может перемешиваться
                print(f"Поток # {thread_hash}: шаг {counter}")
                
                # time.sleep(0.1) - ИМИТАЦИЯ РАБОТЫ:
                # - Аналог Thread.Sleep(100) в C#
                # - Задержка 0.1 секунды = 100 миллисекунд
                # - Увеличивает вероятность переключения между потоками
                time.sleep(0.1)
            
            # РАЗДЕЛИТЕЛЬ для визуального отделения работы потоков
            print('-' * 20)
            
        finally:
            # КОНЕЦ КРИТИЧЕСКОЙ СЕКЦИИ
            # lock.release() - ОСВОБОЖДЕНИЕ БЛОКИРОВКИ:
            # - ОБЯЗАТЕЛЬНО вызывается в finally для гарантии освобождения
            # - Если не освободить - другие потоки заблокируются навсегда (deadlock)
            # - В Python try-finally ОБЯЗАТЕЛЕН при явном acquire()
            self.lock.release()  # Закомментировать вместе с acquire


def main():
    """
    ГЛАВНАЯ ФУНКЦИЯ - аналог Main() в C#
    """
    
    # СОЗДАНИЕ ЭКЗЕМПЛЯРА КЛАССА:
    # - Один объект MyClass используется всеми потоками
    # - Все потоки разделяют один объект lock для синхронизации
    instance = MyClass()
    
    # СПИСОК ДЛЯ ХРАНЕНИЯ ПОТОКОВ:
    # - В Python нужно сохранять ссылки на потоки
    # - Иначе они могут быть собраны garbage collector
    threads = []
    
    # СОЗДАНИЕ И ЗАПУСК 3 ПОТОКОВ:
    for i in range(3):
        # КОНСТРУКЦИЯ СОЗДАНИЯ ПОТОКА в Python:
        # threading.Thread(target=instance.method)
        # - target - функция или метод для выполнения в потоке
        # - Не требуется аналог делегата ThreadStart как в C#
        
        # СОЗДАНИЕ ОБЪЕКТА ПОТОКА:
        # - Поток создается, но еще не запускается
        thread = threading.Thread(target=instance.method)
        
        # СОХРАНЕНИЕ ССЫЛКИ НА ПОТОК:
        # - Добавляем в список для предотвращения GC
        threads.append(thread)
        
        # ЗАПУСК ПОТОКА:
        # thread.start() - аналог Thread.Start() в C#
        # - Поток переходит в состояние "готов к выполнению"
        # - Фактический запуск зависит от GIL и планировщика ОС
        thread.start()
    
    # time.sleep(0.5) - ЗАДЕРЖКА ГЛАВНОГО ПОТОКА:
    # - Дает время рабочим потокам начать выполнение
    # - Аналог Thread.Sleep(500) в C#
    time.sleep(0.5)
    
    # ОЖИДАНИЕ ЗАВЕРШЕНИЯ ВСЕХ ПОТОКОВ:
    # - В отличие от C#, в Python главный поток не ждет автоматически дочерние
    for thread in threads:
        # thread.join() - ОЖИДАНИЕ ЗАВЕРШЕНИЯ ПОТОКА:
        # - Главный поток блокируется до завершения указанного потока
        # - Гарантирует, что приложение не закроется до завершения рабочих потоков
        thread.join()
    
    # input() - ОЖИДАНИЕ ВВОДА (опционально):
    # - Аналог Console.ReadKey() в C#
    # - Можно использовать для паузы перед закрытием консоли
    input("Нажмите Enter для выхода...")


# ТОЧКА ВХОДА в Python приложении:
if __name__ == "__main__":
    main()