using System;
using System.Threading;

// Критическая секция (critical section).

// lock - это сокращенное использование System.Threading.Monitor.
// Monitor.Enter(this) - блокирует блок кода так, что его может использовать только
// текущий поток. 
// Все остальные потоки ждут пока текущий поток, закончит работу и вызовет
// Monitor.Exit(this).

namespace CriticalSection
{
    class MyClass
    {
        /*
        ОБЪЕКТ БЛОКИРОВКИ ( synchronization object ):
        - Создается как простой object, но используется для координации потоков
        - Важно: это НЕ приватное поле - архитектурная ошибка в реальных проектах
        - В продакшн-коде должно быть: private readonly object _block = new object();
        - Каждый поток пытается захватить монитор этого объекта
        */
        object block = new object();

        // МЕТОД ЗАПУСКАЕМЫЙ В ПОТОКЕ:
        // - Вызывается одновременно из нескольких потоков
        // - Каждый вызов работает в своем потоке с общим ресурсом (Console)
        public void Method()
        {
            // ХЭШ ПОТОКА - уникальный идентификатор:
            // - GetHashCode() возвращает числовой идентификатор потока
            // - В реальных приложениях лучше использовать ManagedThreadId
            int hash = Thread.CurrentThread.GetHashCode();

            /*
            КРИТИЧЕСКАЯ СЕКЦИЯ с Monitor:
            - Monitor.Enter/Exit - РУЧНОЕ управление блокировкой
            - ОПАСНО: если между Enter и Exit возникнет исключение - блокировка НЕ снимется
            - В отличие от lock, который автоматически снимает блокировку
            */

            /* НАЧАЛО КРИТИЧЕСКОЙ СЕКЦИИ */

            // Monitor.Enter(block) - ПОПЫТКА ЗАХВАТА МОНИТОРА:
            // - Если монитор свободен - поток захватывает его и продолжает выполнение
            // - Если монитор занят - поток БЛОКИРУЕТСЯ до освобождения
            // - После захвата монитора, поток получает эксклюзивный доступ к блоку кода
            Monitor.Enter(block); // Закомментировать для демонстрации гонки данных

            // ТЕЛО КРИТИЧЕСКОЙ СЕКЦИИ:
            // - Весь этот код выполняется ТОЛЬКО одним потоком одновременно
            // - Другие потоки ждут на Monitor.Enter(block)
            for (int counter = 0; counter < 10; counter++)
            {
                // РАЗДЕЛЯЕМЫЙ РЕСУРС - объект Console:
                // - Все потоки пытаются писать в консоль одновременно
                // - Без синхронизации вывод перемешивается
                Console.WriteLine("Поток # {0}: шаг {1}", hash, counter);

                // Thread.Sleep(100) - ИМИТАЦИЯ РАБОТЫ:
                // - Задержка 100мс имитирует выполнение полезной работы
                // - Увеличивает вероятность переключения контекста между потоками
                // - Без sleep потоки могут выполняться слишком быстро для демонстрации гонки
                Thread.Sleep(100);
            }

            // РАЗДЕЛИТЕЛЬ для визуального отделения работы каждого потока
            Console.WriteLine(new string('-', 20));

            /* КОНЕЦ КРИТИЧЕСКОЙ СЕКЦИИ */

            // Monitor.Exit(block) - ОСВОБОЖДЕНИЕ МОНИТОРА:
            // - Обязательно должен быть вызван после Enter
            // - Если не вызвать - монитор останется захваченным (deadlock)
            // - В реальном коде нужно использовать try-finally для гарантии вызова
            Monitor.Exit(block);  // Закомментировать вместе с Enter

        }
    }

    class Program
    {
        static void Main()
        {
            // НАСТРОЙКА КОНСОЛИ:
            // - Установка размера окна для удобного просмотра вывода
            Console.SetWindowSize(80, 40);

            // СОЗДАНИЕ ЭКЗЕМПЛЯРА КЛАССА:
            // - Один объект MyClass используется всеми потоками
            // - Все потоки разделяют один объект block для синхронизации
            MyClass instance = new MyClass();

            // СОЗДАНИЕ И ЗАПУСК ПОТОКОВ:
            // - Создается 3 потока, которые одновременно вызывают instance.Method()
            for (int i = 0; i < 3; i++)
            {
                // КОНСТРУКЦИЯ СОЗДАНИЯ ПОТОКА:
                // new Thread(instance.Method).Start() состоит из:
                // 
                // 1. instance.Method - метод для выполнения в потоке
                // 2. Неявное создание делегата ThreadStart(instance.Method)
                //    - ThreadStart - делегат без параметров, возвращающий void
                //    - Компилятор автоматически создает: new ThreadStart(instance.Method)
                // 3. new Thread(delegate) - создание объекта потока
                // 4. .Start() - запуск потока (не путать с запуском метода)

                // ВАЖНО: Start() НЕ вызывает метод немедленно!
                // - Поток переходит в состояние "готов к выполнению"
                // - Фактический запуск зависит от планировщика потоков ОС
                new Thread(instance.Method).Start();
            }

            // Thread.Sleep(500) - ЗАДЕРЖКА ГЛАВНОГО ПОТОКА:
            // - Дает время рабочим потокам начать выполнение
            // - Без этой задержки главный поток может сразу перейти к ReadKey()
            Thread.Sleep(500);

            // Console.ReadKey() - ОЖИДАНИЕ КЛАВИШИ:
            // - Предотвращает закрытие консоли до завершения работы потоков
            // - Без этого приложение завершится сразу после выхода из Main
            Console.ReadKey();
        }
    }
}