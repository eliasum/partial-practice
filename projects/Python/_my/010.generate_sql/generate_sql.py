# Основная функция нашего скрипта
def main():
    # ОТКРЫВАЕМ ФАЙЛ ДЛЯ ЧТЕНИЯ
    # 'r' означает режим чтения, encoding='utf-8' для правильного отображения русских букв
    file = open("ЕО Единица транспортировки.txt", "r", encoding="utf-8")

    # ЧИТАЕМ ВСЕ СТРОКИ ИЗ ФАЙЛА
    # readlines() читает все строки и возвращает список строк
    all_lines = file.readlines()

    # ЗАКРЫВАЕМ ФАЙЛ - это важно делать после работы с файлом
    file.close()

    # СОЗДАЕМ НОВЫЙ ФАЙЛ ДЛЯ SQL-СКРИПТА
    # 'w' означает режим записи (если файл существует, он будет перезаписан)
    sql_file = open("update_database.sql", "w", encoding="utf-8")

    # ЗАПИСЫВАЕМ ПЕРВУЮ СТРОКУ SQL-СКРИПТА
    sql_file.write("USE [hydra1]\nGO\n\n")

    # ПЕРЕМЕННАЯ ДЛЯ ПОДСЧЕТА ОБРАБОТАННЫХ СТРОК
    count = 0

    # ОБРАБАТЫВАЕМ КАЖДУЮ СТРОКУ ИЗ ФАЙЛА
    # enumerate(all_lines) возвращает пары (номер_строки, содержимое_строки)
    for line_number, line_text in enumerate(all_lines):
        # ПРОПУСКАЕМ ПЕРВУЮ СТРОКУ (ЗАГОЛОВОК)
        # line_number = 0 это первая строка, нам она не нужна
        if line_number == 0:
            continue  # переходим к следующей строке

        # УДАЛЯЕМ ЛИШНИЕ ПРОБЕЛЫ И ПЕРЕВОДЫ СТРОК
        clean_line = line_text.strip()

        # ПРОВЕРЯЕМ, ЧТО СТРОКА НЕ ПУСТАЯ
        if clean_line == "":
            continue  # если строка пустая, переходим к следующей

        # РАЗДЕЛЯЕМ СТРОКУ НА ДВЕ ЧАСТИ
        # Ищем где заканчиваются цифры ЕО и начинается единица транспортировки
        # Предполагаем, что разделитель - это один или несколько пробелов/табуляций
        parts = (
            clean_line.split()
        )  # split() без параметров разделяет по любому количеству пробелов/табуляций

        # ПРОВЕРЯЕМ, ЧТО В СТРОКЕ ЕСТЬ ОБА ЗНАЧЕНИЯ
        if len(parts) < 2:
            continue  # если в строке меньше 2 частей, пропускаем ее

        # ПЕРВАЯ ЧАСТЬ - ЕО (значение для id_sap_toro)
        eo_value = parts[0]

        # ВТОРАЯ ЧАСТЬ - Единица транспортировки (значение для trans_einh)
        trans_einh_value = parts[1]

        # ОБРАБАТЫВАЕМ СЛУЧАЙ С "#Н/Д"
        if eo_value == "#Н/Д":
            # Если значение "#Н/Д", то в SQL мы используем NULL
            sql_value = "NULL"
        else:
            # Если нормальное значение, оборачиваем его в кавычки для SQL
            sql_value = (
                f"'{eo_value}'"  # f-строка позволяет вставлять переменные в текст
            )

        # ФОРМИРУЕМ SQL-ЗАПРОС ДЛЯ ОДНОЙ СТРОКИ
        # Это команда UPDATE которая обновляет запись в таблице
        sql_query = f"UPDATE [hydadm].[u_tpe_info] SET id_sap_toro = {sql_value} WHERE trans_einh = '{trans_einh_value}';\n"

        # ЗАПИСЫВАЕМ SQL-ЗАПРОС В ФАЙЛ
        sql_file.write(sql_query)

        # УВЕЛИЧИВАЕМ СЧЕТЧИК ОБРАБОТАННЫХ СТРОК
        count += 1

        # ВЫВОДИМ ПРОГРЕСС НА ЭКРАН (каждые 100 строк)
        if count % 100 == 0:
            print(f"Обработано {count} строк...")

    # ЗАКРЫВАЕМ SQL-ФАЙЛ
    sql_file.close()

    # ВЫВОДИМ ИТОГОВОЕ СООБЩЕНИЕ
    print("=" * 50)
    print("ГЕНЕРАЦИЯ SQL-СКРИПТА ЗАВЕРШЕНА!")
    print(f"Обработано строк: {count}")
    print("Создан файл: update_database.sql")
    print("=" * 50)
    print("\nЧТО ДЕЛАТЬ ДАЛЬШЕ:")
    print("1. Откройте SQL Server Management Studio")
    print("2. Подключитесь к вашей базе данных")
    print("3. Откройте файл update_database.sql")
    print("4. Выполните скрипт (нажмите F5)")


# ЭТА ПРОВЕРКА НУЖНА, ЧТОБЫ ФУНКЦИЯ main ВЫПОЛНИЛАСЬ ТОЛЬКО ПРИ ПРЯМОМ ЗАПУСКЕ ФАЙЛА
if __name__ == "__main__":
    # ВЫЗЫВАЕМ ОСНОВНУЮ ФУНКЦИЮ
    main()
