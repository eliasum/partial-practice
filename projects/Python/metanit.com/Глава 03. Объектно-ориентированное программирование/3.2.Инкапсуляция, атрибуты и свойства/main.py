# Методы доступа. Геттеры и сеттеры

# Может возникнуть вопрос, как обращаться к подобным приватным атрибутам.
# Для этого обычно применяются специальные методы доступа. Геттер позволяет
# получить значение атрибута, а сеттер установить его. Так, изменим выше
# определенный класс, определив в нем методы доступа:


class Person:
    def __init__(self, name, age):  # дАндер-инИт
        self.__name = name  # устанавливаем имя селф дабл-андерскор нейм
        self.__age = age  # устанавливаем возраст селф дабл-андерскор эйдж

    # сеттер для установки возраста
    def set_age(self, age):
        if 0 < age < 110:
            self.__age = age  # устанавливаем возраст селф дабл-андерскор эйдж
        else:
            print("Недопустимый возраст")

    # геттер для получения возраста
    def get_age(self):
        return self.__age

    # геттер для получения имени
    def get_name(self):
        return self.__name

    def print_person(self):
        print(f"Имя: {self.__name}\tВозраст: {self.__age}")


tom = Person("Tom", 39)
tom.print_person()  # Имя: Tom  Возраст: 39
tom.set_age(-3486)  # Недопустимый возраст
tom.set_age(25)
tom.print_person()  # Имя: Tom  Возраст: 25

