# Причем опосредование доступа к атрибутам через методы позволяет задать
# дополнительную логику. Так, в зависимости от переданного возраста мы
# можем решить, надо ли переустанавливать возраст, так как переданное
# значение может быть некорректным.

# Также необязательно создавать для каждого приватного атрибута подобную
# пару методов. Так, в примере выше имя человека мы можем установить
# только из конструктора. А для получение определен метод get_name.

# Аннотации свойств

# Выше мы рассмотрели, как создавать методы доступа. Но Python имеет
# также еще один - более элегантный способ - свойства. Этот способ
# предполагает использование аннотаций, которые предваряются символом @.

# Для создания свойства-геттера над свойством ставится аннотация @property.

# Для создания свойства-сеттера над свойством устанавливается аннотация
# имя_свойства_геттера.setter.

# Перепишем класс Person с использованием аннотаций:


class Person:
    def __init__(self, name, age):  # дАндер-инИт
        self.__name = name  # устанавливаем имя селф дабл-андерскор нейм
        self.__age = age  # устанавливаем возраст селф дабл-андерскор эйдж

    # свойство-геттер
    @property
    def age(self):
        return self.__age

    # свойство-сеттер
    @age.setter
    def age(self, age):
        if 0 < age < 110:
            self.__age = age
        else:
            print("Недопустимый возраст")

    @property
    def name(self):
        return self.__name

    def print_person(self):
        print(f"Имя: {self.__name}\tВозраст: {self.__age}")


tom = Person("Tom", 39)
tom.print_person()  # Имя: Tom  Возраст: 39
tom.age = -3486  # Недопустимый возраст  (Обращение к сеттеру)
print(tom.age)  # 39 (Обращение к геттеру)
tom.age = 25  # (Обращение к сеттеру)
tom.print_person()  # Имя: Tom  Возраст: 25

# Во-первых, стоит обратить внимание, что свойство-сеттер определяется после свойства-геттера.

# Во-вторых, и сеттер, и геттер называются одинаково - age. И поскольку геттер
# называется age, то над сеттером устанавливается аннотация @age.setter.

# После этого, что к геттеру, что к сеттеру, мы обращаемся через выражение tom.age.

# При этом можно определить только геттер, как в случае с свойством name -
# его нельзя изменить, а можно лишь получить значение.
